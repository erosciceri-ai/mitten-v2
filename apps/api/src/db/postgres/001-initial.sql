-- This is a logical table; actual rows created per user

-- Sync sessions table (for tracking active sync transactions)
CREATE TABLE sync_sessions (
  sync_id TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  profile_id TEXT NOT NULL,
  profile_revision TEXT NOT NULL,
  expected_gesture_count BIGINT NOT NULL,
  received_count BIGINT DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'active',  -- 'active', 'committed', 'aborted', 'failed'
  created_at TEXT DEFAULT mitten_timestamp(),
  updated_at TEXT DEFAULT mitten_timestamp(),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_sync_sessions_user_id ON sync_sessions(user_id);
CREATE INDEX idx_sync_sessions_status ON sync_sessions(status);

-- Sync gestures staging table (temporary storage during sync transaction)
CREATE TABLE sync_gestures_staging (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 9007199254740991) PRIMARY KEY,
  sync_id TEXT NOT NULL,
  gesture_index BIGINT NOT NULL,
  gesture_id BIGINT NOT NULL,
  name TEXT NOT NULL,
  audio_track BIGINT NOT NULL,
  data TEXT NOT NULL,  -- JSON serialized GestureData
  created_at TEXT DEFAULT mitten_timestamp(),
  FOREIGN KEY (sync_id) REFERENCES sync_sessions(sync_id) ON DELETE CASCADE,
  UNIQUE(sync_id, gesture_index)
);

CREATE INDEX idx_sync_gestures_staging_sync_id ON sync_gestures_staging(sync_id);

CREATE FUNCTION mitten_update_timestamp() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := mitten_timestamp();
  RETURN NEW;
END;
$$;

CREATE TRIGGER update_users_timestamp BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION mitten_update_timestamp();
CREATE TRIGGER update_gestures_timestamp BEFORE UPDATE ON gestures
  FOR EACH ROW EXECUTE FUNCTION mitten_update_timestamp();
CREATE TRIGGER update_profiles_timestamp BEFORE UPDATE ON profiles
  FOR EACH ROW EXECUTE FUNCTION mitten_update_timestamp();
CREATE TRIGGER update_sync_sessions_timestamp BEFORE UPDATE ON sync_sessions
  FOR EACH ROW EXECUTE FUNCTION mitten_update_timestamp();
