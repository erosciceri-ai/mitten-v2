-- Preserve SQLite's UTC timestamp strings and serialized gesture data.
CREATE FUNCTION mitten_timestamp() RETURNS text LANGUAGE sql STABLE AS $$
  SELECT to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
$$;

-- Users table
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 9007199254740991) PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  password_hash TEXT,
  google_sub TEXT,
  created_at TEXT DEFAULT mitten_timestamp(),
  updated_at TEXT DEFAULT mitten_timestamp(),
  CHECK(password_hash IS NOT NULL OR google_sub IS NOT NULL)
);

-- Index for email lookups
CREATE INDEX idx_users_email ON users(email);
CREATE UNIQUE INDEX idx_users_google_sub ON users(google_sub) WHERE google_sub IS NOT NULL;

-- Gestures table
CREATE TABLE gestures (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 2147483647),
  user_id BIGINT NOT NULL,
  name TEXT NOT NULL,
  audio_track INTEGER NOT NULL CHECK(audio_track BETWEEN 1 AND 50),
  data TEXT NOT NULL,  -- JSON serialized GestureData
  created_at TEXT DEFAULT mitten_timestamp(),
  updated_at TEXT DEFAULT mitten_timestamp(),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  UNIQUE(user_id, id),
  UNIQUE(user_id, audio_track),
  UNIQUE(user_id, id, audio_track)
);

-- Index for user's gestures
CREATE INDEX idx_gestures_user_id ON gestures(user_id);
CREATE INDEX idx_gestures_audio_track ON gestures(audio_track);

-- Profiles table (for sync metadata)
CREATE TABLE profiles (
  id TEXT PRIMARY KEY,  -- Profile ID (UUID or similar)
  user_id BIGINT NOT NULL,
  revision TEXT NOT NULL,
  gesture_count BIGINT DEFAULT 0,
  created_at TEXT DEFAULT mitten_timestamp(),
  updated_at TEXT DEFAULT mitten_timestamp(),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Index for user's profiles
CREATE INDEX idx_profiles_user_id ON profiles(user_id);

-- Audio tracks table (tracks 1-50, for MP3 file management)
CREATE TABLE audio_tracks (
  track_number INTEGER NOT NULL CHECK(track_number BETWEEN 1 AND 50),
  user_id BIGINT NOT NULL,
  gesture_id INTEGER,  -- NULL if available
  file_path TEXT,  -- Path to MP3 file on disk
  generated_at TEXT,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, track_number),
  FOREIGN KEY (user_id, gesture_id, track_number) REFERENCES gestures(user_id, id, audio_track)
);

